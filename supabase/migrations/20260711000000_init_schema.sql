-- ConvertBrio core schema: user profiles, conversion jobs, and Razorpay subscriptions.
-- Run this in the Supabase SQL editor (or `supabase db push`) once the project exists.

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null,
  plan text not null default 'free' check (plan in ('free', 'pro', 'business')),
  razorpay_customer_id text,
  created_at timestamptz not null default now()
);

create table if not exists public.conversion_jobs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users (id) on delete cascade,
  tool_slug text not null,
  status text not null default 'pending' check (status in ('pending', 'processing', 'completed', 'failed')),
  input_path text,
  output_path text,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '1 hour')
);

create index if not exists conversion_jobs_user_id_idx on public.conversion_jobs (user_id);
create index if not exists conversion_jobs_expires_at_idx on public.conversion_jobs (expires_at);

create table if not exists public.subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  razorpay_subscription_id text unique,
  plan text not null check (plan in ('pro', 'business')),
  status text not null default 'created',
  current_period_end timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists subscriptions_user_id_idx on public.subscriptions (user_id);

-- Auto-create a profile row whenever someone signs up.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email);
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Row Level Security: end users may only ever read their own rows.
-- All writes to these tables happen server-side via the service-role key
-- (API routes, webhooks, the cleanup cron), so no client-facing
-- insert/update/delete policies are defined.
alter table public.profiles enable row level security;
alter table public.conversion_jobs enable row level security;
alter table public.subscriptions enable row level security;

create policy "Users can view their own profile" on public.profiles
  for select using (auth.uid() = id);

create policy "Users can view their own conversion jobs" on public.conversion_jobs
  for select using (auth.uid() = user_id);

create policy "Users can view their own subscriptions" on public.subscriptions
  for select using (auth.uid() = user_id);

-- Private bucket for converted files. Only the service-role key (used
-- server-side) can read/write it; end users get files via signed URLs
-- generated by the API routes, or the direct download response.
insert into storage.buckets (id, name, public)
values ('conversions', 'conversions', false)
on conflict (id) do nothing;
